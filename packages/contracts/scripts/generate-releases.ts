/**
 * Generates releases.ts from releases/: the runtime record of each release's GianoPaymaster, so a
 * chain's paymaster implementation can be matched to the release it runs (D13).
 *
 * The records are in release.json already (`pnpm release:runtime`, checked by `release:verify`);
 * this only carries them into the TypeScript surface without the creation code, which is most of
 * a release's weight.
 *
 *   pnpm gen:releases            (no solc, no network; CI fails on drift)
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { listReleases, loadRelease } from "../deploy/release";

const outPath = path.resolve(import.meta.dirname, "..", "releases.ts");

const entries = listReleases().map((version) => {
	const runtime = loadRelease(version).contracts.GianoPaymaster.runtime;
	if (!runtime)
		throw new Error(
			`${version}: GianoPaymaster has no runtime record; run \`pnpm release:runtime\``,
		);
	const ranges = runtime.immutables
		.map(({ start, length }) => `{ start: ${start}, length: ${length} }`)
		.join(", ");
	return `  { release: '${version}', codehash: '${runtime.codehash}', immutables: [${ranges}] },`;
});

const output = `// AUTO-GENERATED by scripts/generate-releases.ts — do not edit by hand.
// Input: the runtime records in releases/*/release.json. Regenerate with: pnpm gen:releases
// (CI fails on drift).
import { type Hex, hexToBytes, keccak256 } from 'viem';

/**
 * One release's GianoPaymaster runtime code: its hash with every immutable zeroed, and where the
 * immutables are. An immutable (UUPS's own address, EIP-712's cached domain) differs per
 * deployment, so code read from a chain is zeroed at those ranges before it is hashed.
 */
export type PaymasterRelease = {
  release: string;
  codehash: Hex;
  immutables: readonly { start: number; length: number }[];
};

/** Every release's GianoPaymaster, oldest first. */
export const PAYMASTER_RELEASES: readonly PaymasterRelease[] = [
${entries.join("\n")}
];

/** The release whose GianoPaymaster \`code\` is (the runtime code at an implementation), if any. */
export function paymasterReleaseOf(code: Hex): PaymasterRelease | undefined {
  const bytes = hexToBytes(code);
  return PAYMASTER_RELEASES.find((entry) => {
    const zeroed = bytes.slice();
    for (const { start, length } of entry.immutables) {
      if (start + length > zeroed.length) return false;
      zeroed.fill(0, start, start + length);
    }
    return keccak256(zeroed).toLowerCase() === entry.codehash.toLowerCase();
  });
}
`;

fs.writeFileSync(outPath, output);
console.log(
	`Wrote ${path.relative(process.cwd(), outPath)} (${listReleases().join(", ")})`,
);
