/**
 * Generates release-fingerprints.ts: per release and deployable contract, the code fingerprint that
 * release-code.ts's `releaseOf` matches on-chain code against.
 *
 * Each release is compiled from its committed standard-JSON input with plain solc
 * (deploy/release-compile.ts). The fingerprint is the keccak256 of the runtime code with every
 * immutable zeroed; solc emits immutables as zeroes, so that is the hash of solc's runtime code.
 *
 *   pnpm gen:releases            (needs each release's solc; CI fails on drift)
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { keccak256 } from "viem";
import { listReleases, RELEASE_CONTRACTS } from "../deploy/release";
import { compileRelease } from "../deploy/release-compile";

const outPath = path.resolve(
	import.meta.dirname,
	"..",
	"release-fingerprints.ts",
);

function main(): void {
	const releases = listReleases();
	if (releases.length === 0)
		throw new Error("no releases; cut one first (pnpm release:cut v1)");

	const entries: string[] = [];
	for (const version of releases) {
		const compiled = compileRelease(version);
		// RELEASE_CONTRACTS order, so the file does not depend on solc's output order.
		for (const contract of Object.keys(
			RELEASE_CONTRACTS,
		) as (keyof typeof RELEASE_CONTRACTS)[]) {
			const code = compiled[contract];
			if (!code) continue; // an older release that predates the contract
			const immutables = code.immutables.flatMap(({ name, ranges }) =>
				ranges.map(({ start, length }) => ({ name, start, length })),
			);
			immutables.sort((a, b) => a.start - b.start);
			for (const { name, start, length } of immutables) {
				const bytes = code.runtimeCode.slice(
					2 + start * 2,
					2 + (start + length) * 2,
				);
				if (!/^0+$/.test(bytes))
					throw new Error(
						`${version} ${contract}: immutable ${name} is not zero in solc's runtime code`,
					);
			}
			const fingerprint = keccak256(code.runtimeCode);
			const lines = immutables
				.map(
					(i) =>
						`      { name: '${i.name}', start: ${i.start}, length: ${i.length} },`,
				)
				.join("\n");
			entries.push(`  {
    contract: '${contract}',
    release: '${version}',
    size: ${(code.runtimeCode.length - 2) / 2},
    immutables: [${lines ? `\n${lines}\n    ` : ""}],
    fingerprint: '${fingerprint}',
  },`);
		}
	}

	const contractNames = Object.keys(RELEASE_CONTRACTS)
		.map((name) => `  | '${name}'`)
		.join("\n");
	const output = `// AUTO-GENERATED by scripts/generate-releases.ts — do not edit by hand.
// Inputs: releases/<version>/standard-input.json. Regenerate with: pnpm gen:releases
// (CI fails on drift). Match code against these with releaseOf (release-code.ts).

/** Every contract a release can carry (deploy/release.ts). */
export type ReleaseContractName =
${contractNames};

/** One release of one contract: what its runtime code hashes to with the immutables masked. */
export type ReleaseFingerprint = {
  contract: ReleaseContractName;
  release: string;
  /** Runtime code size in bytes. */
  size: number;
  /** Byte ranges of the runtime code that hold an immutable, named \`<declaring contract>.<variable>\`. */
  immutables: readonly { name: string; start: number; length: number }[];
  /** keccak256 of the runtime code with every immutable range zeroed. */
  fingerprint: \`0x\${string}\`;
};

export const RELEASE_FINGERPRINTS: readonly ReleaseFingerprint[] = [
${entries.join("\n")}
];
`;
	fs.writeFileSync(outPath, output);
	console.log(
		`Wrote ${path.relative(process.cwd(), outPath)} (${releases.join(", ")}; ${entries.length} contracts)`,
	);
}

main();
