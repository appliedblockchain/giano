/**
 * Generates the fixture artifacts under fixtures/ (deploy/fixtures.ts): per fixture contract, its
 * creation code and fingerprint from a Foundry build of src/.
 *
 * It runs the same build as `pnpm gen:abis` (out-abi/, cache_forge_abi/), so after gen:abis it
 * compiles nothing. The fingerprint is computed as for a release (scripts/generate-releases.ts): the
 * keccak256 of the runtime code. A fixture with an immutable is refused, so nothing needs masking.
 *
 * When a fixture's code changes, the committed artifact's fingerprint moves to `previous`, so a chain
 * that holds the earlier code still matches (deploy/fixtures.ts). The artifact it replaces is the one
 * at git HEAD, not the working copy: running this again before a commit adds no version that was never
 * committed, and so never deployed.
 *
 *   pnpm gen:fixtures            rewrite fixtures/
 *   pnpm gen:fixtures --check    fail if fixtures/ does not match the source (CI)
 */
import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import { type Hex, keccak256 } from "viem";
import {
	FIXTURE_CONTRACTS,
	FIXTURES_DIR,
	type FixtureArtifact,
	type FixtureContractName,
	previousVersions,
} from "../deploy/fixtures";

const pkgRoot = path.resolve(import.meta.dirname, "..");

type ForgeArtifact = {
	bytecode: { object: Hex };
	deployedBytecode: {
		object: Hex;
		immutableReferences?: Record<string, unknown[]>;
	};
	metadata: { compiler: { version: string } };
};

function build(): void {
	execFileSync(
		"forge",
		["build", "src", "--out", "out-abi", "--cache-path", "cache_forge_abi"],
		{ cwd: pkgRoot, stdio: ["ignore", "ignore", "inherit"] },
	);
}

/**
 * The artifact committed at git HEAD, or undefined when HEAD has none (a new fixture). Outside a git
 * checkout, the working copy.
 */
function committedArtifact(file: string): FixtureArtifact | undefined {
	const git = (args: string[]) =>
		execFileSync("git", args, {
			cwd: pkgRoot,
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
		});
	try {
		git(["rev-parse", "--verify", "HEAD"]);
	} catch {
		const target = path.join(FIXTURES_DIR, file);
		return fs.existsSync(target)
			? (JSON.parse(fs.readFileSync(target, "utf8")) as FixtureArtifact)
			: undefined;
	}
	try {
		return JSON.parse(
			git(["show", `HEAD:./fixtures/${file}`]),
		) as FixtureArtifact;
	} catch {
		return undefined;
	}
}

function artifactText(contract: FixtureContractName): string {
	const { source, file } = FIXTURE_CONTRACTS[contract];
	// forge names an artifact after its source file.
	const forge = JSON.parse(
		fs.readFileSync(
			path.join(pkgRoot, "out-abi", path.basename(source), `${contract}.json`),
			"utf8",
		),
	) as ForgeArtifact;
	if (Object.keys(forge.deployedBytecode.immutableReferences ?? {}).length)
		throw new Error(
			`${contract} has immutables; a fixture's fingerprint masks none`,
		);
	const runtime = forge.deployedBytecode.object;
	const fingerprint = keccak256(runtime);
	const artifact: FixtureArtifact = {
		$comment: `Generated by scripts/generate-fixtures.ts from ${source} (pnpm gen:fixtures). Do not edit; CI fails on drift. See fixtures/README.md.`,
		contract,
		source,
		solc: forge.metadata.compiler.version,
		creationCode: forge.bytecode.object,
		runtimeCode: runtime,
		size: (runtime.length - 2) / 2,
		fingerprint,
		previous: previousVersions(committedArtifact(file), fingerprint),
	};
	return `${JSON.stringify(artifact, null, "\t")}\n`;
}

function main(): void {
	const check = process.argv.includes("--check");
	build();
	const stale: string[] = [];
	for (const contract of Object.keys(
		FIXTURE_CONTRACTS,
	) as FixtureContractName[]) {
		const { source, file } = FIXTURE_CONTRACTS[contract];
		const target = path.join(FIXTURES_DIR, file);
		const text = artifactText(contract);
		const current = fs.existsSync(target)
			? fs.readFileSync(target, "utf8")
			: undefined;
		if (current === text) {
			console.log(`fixtures/${file} matches ${source}`);
			continue;
		}
		if (check) stale.push(`fixtures/${file}`);
		else {
			fs.writeFileSync(target, text);
			console.log(`wrote fixtures/${file}`);
		}
	}
	if (stale.length) {
		console.error(
			`${stale.join(", ")} does not match the source; run \`pnpm gen:fixtures\` and commit the result`,
		);
		process.exit(1);
	}
}

main();
