// Writes src/generated/simulations.ts from the eth-infinitism v0.7 release artifacts: the runtime
// code the estimator installs at the EntryPoint address with an eth_call state override, and the
// two simulation functions it calls. `--check` fails instead of writing when the file is stale.
//
//   node scripts/generate-simulations.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const simulations = require('@account-abstraction/contracts/artifacts/EntryPointSimulations.json');
const senderCreator = require('@account-abstraction/contracts/artifacts/SenderCreator.json');
const { version } = require('@account-abstraction/contracts/package.json');

const abi = simulations.abi.filter(
  (item) => item.type === 'function' && (item.name === 'simulateHandleOp' || item.name === 'simulateValidation'),
);

const source = `// GENERATED by scripts/generate-simulations.mjs from @account-abstraction/contracts@${version} — do not edit.

/** EntryPointSimulations runtime code, installed at the EntryPoint address by state override. */
export const entryPointSimulationsCode = '${simulations.deployedBytecode}' as const;

/**
 * SenderCreator runtime code. EntryPointSimulations calls the SenderCreator at the EntryPoint's first
 * CREATE address; a devnet whose EntryPoint was installed with anvil_setCode has none there.
 */
export const senderCreatorCode = '${senderCreator.deployedBytecode}' as const;

export const entryPointSimulationsAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

const target = fileURLToPath(new URL('../src/generated/simulations.ts', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) {
    console.error('src/generated/simulations.ts is stale: run node scripts/generate-simulations.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, source);
}
